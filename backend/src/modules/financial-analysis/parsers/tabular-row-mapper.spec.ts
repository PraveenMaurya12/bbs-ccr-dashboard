import { mapTabularRows } from './tabular-row-mapper'

describe('mapTabularRows', () => {
  it('CRITICAL: never routes the Deposit/Credit column into the Description/narration column just because "description" contains the substring "cr"', () => {
    // A very common real-world export shape: "Description" as the
    // narration header, separate Withdrawal/Deposit amount columns. A
    // prior bug's bare `.includes('cr')` check matched "description"
    // (des-CR-iption) before ever reaching the real "Deposit Amt" column,
    // silently discarding every credit/income transaction.
    const rows = [
      ['Date', 'Description', 'Chq No', 'Value Date', 'Withdrawal Amt', 'Deposit Amt', 'Closing Balance'],
      ['05/01/2026', 'SALARY CREDIT ABC CORP', '', '05/01/2026', '', '55000.00', '60000.00'],
      ['10/01/2026', 'EMI AUTO DEBIT', '', '10/01/2026', '6500.00', '', '53500.00'],
    ]

    const result = mapTabularRows(rows)

    expect(result.rows).toHaveLength(2)
    expect(result.rows[0].narration).toBe('SALARY CREDIT ABC CORP')
    expect(result.rows[0].rawCredit).toBe('55000.00')
    expect(result.rows[0].rawDebit).toBeNull()
    expect(result.rows[1].rawDebit).toBe('6500.00')
    expect(result.rows[1].rawCredit).toBeNull()
  })

  it('still correctly maps bare "Cr"/"Dr" column headers (the exact-token case the keyword list exists for)', () => {
    const rows = [
      ['Date', 'Narration', 'Dr', 'Cr', 'Balance'],
      ['01/01/2026', 'ATM WITHDRAWAL', '2000.00', '', '48000.00'],
      ['02/01/2026', 'SALARY', '', '55000.00', '103000.00'],
    ]

    const result = mapTabularRows(rows)

    expect(result.rows).toHaveLength(2)
    expect(result.rows[0].rawDebit).toBe('2000.00')
    expect(result.rows[1].rawCredit).toBe('55000.00')
  })

  it('maps a single signed-amount-column statement correctly', () => {
    const rows = [
      ['Txn Date', 'Particulars', 'Amount', 'Running Balance'],
      ['01/01/2026', 'SALARY CREDIT', '55000.00', '55000.00'],
    ]

    const result = mapTabularRows(rows)

    expect(result.rows).toHaveLength(1)
    expect(result.rows[0].rawAmount).toBe('55000.00')
    expect(result.rows[0].rawDebit).toBeNull()
    expect(result.rows[0].rawCredit).toBeNull()
  })

  it('returns no rows and a clear warning when no recognizable header exists', () => {
    const rows = [['Statement Period: Jan-Dec 2026'], ['Generated by MockBank']]
    const result = mapTabularRows(rows)
    expect(result.rows).toHaveLength(0)
    expect(result.warnings[0]).toMatch(/no recognizable header/i)
  })

  it('skips a footer/separator row with no date and no amount signal, never fabricating a transaction', () => {
    const rows = [
      ['Date', 'Narration', 'Debit', 'Credit', 'Balance'],
      ['01/01/2026', 'SALARY', '', '55000.00', '55000.00'],
      ['', 'End of Statement', '', '', ''],
    ]
    const result = mapTabularRows(rows)
    expect(result.rows).toHaveLength(1)
  })
})

describe('mapTabularRows — BAL column detection (Bug 1 regression)', () => {
  // A real confirmed bug: a statement header naming the balance column with
  // the bare abbreviation "BAL" (e.g. this module's own real Axis Bank CSV
  // fixture: "Tran Date,CHQNO,PARTICULARS,DR,CR,BAL,SOL") was never
  // recognized, because HEADER_KEYWORDS.balance only listed the spelled-out
  // forms — every transaction's balance silently came back null, and
  // liquidity/closing-balance became NOT_REPORTED even though the file
  // genuinely reports a running balance.
  const casesThatMustMatch: Array<[string, string]> = [
    ['BAL', 'all-caps abbreviation (the real bug report)'],
    ['Bal', 'title-case abbreviation'],
    ['bal', 'lowercase abbreviation'],
    ['Balance', 'already-working spelled-out form'],
    ['Closing Balance', 'already-working spelled-out form'],
    ['Running Balance', 'already-working spelled-out form'],
    ['Available Balance', 'already-working spelled-out form'],
  ]

  it.each(casesThatMustMatch)('recognizes "%s" as the balance column (%s)', (headerLabel) => {
    const rows = [
      ['Tran Date', 'CHQNO', 'PARTICULARS', 'DR', 'CR', headerLabel, 'SOL'],
      ['01-04-2025', '-', 'UPI/P2M/R CITY MALL/Paid v/BANK OF BARODA', '', '30.00', '19569.55', '4806'],
    ]
    const result = mapTabularRows(rows)
    expect(result.rows).toHaveLength(1)
    expect(result.rows[0].rawBalance).toBe('19569.55')
  })

  it('does NOT match unrelated words merely containing the substring "bal" (word-boundary safety preserved)', () => {
    const rows = [
      ['Date', 'Narration', 'Debit', 'Credit', 'Global Ref', 'Balcony Code'],
      ['01/01/2026', 'SALARY', '', '55000.00', 'G123', 'B456'],
    ]
    const result = mapTabularRows(rows)
    expect(result.rows).toHaveLength(1)
    // Neither "Global Ref" nor "Balcony Code" is the balance column — with
    // no real balance header present, rawBalance must stay null, never
    // accidentally sourced from one of these unrelated columns.
    expect(result.rows[0].rawBalance).toBeNull()
  })
})
