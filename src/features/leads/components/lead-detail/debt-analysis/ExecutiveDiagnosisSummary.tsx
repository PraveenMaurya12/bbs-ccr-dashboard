import { Sparkles } from 'lucide-react'

import type { DebtAnalysisInsights } from '../../../types'
import { getDebtDiagnosisFindings } from './aiFindings'
import { NotAvailable, SectionCard } from '../shared/SectionCard'

/**
 * Layer 1's AI-authored half: the executive summary and current repayment
 * position, advisory only (never a finalized decision — see
 * DebtDiagnosisPanel's own doc comment for the rest of the Layer 5/6 AI
 * output). Replaces the old flat InsightsCard entirely.
 */
export function ExecutiveDiagnosisSummary({ insights }: { insights: DebtAnalysisInsights | null }) {
  const subtitle = <p className="text-xs text-[#5c5c5c]">Advisory only — never a finalized decision</p>

  if (!insights) {
    return (
      <SectionCard icon={Sparkles} title="Executive summary">
        {subtitle}
        <NotAvailable reason="No AI insights have been generated for this report yet." />
      </SectionCard>
    )
  }

  if (insights.status !== 'COMPLETED') {
    return (
      <SectionCard icon={Sparkles} title="Executive summary">
        {subtitle}
        <NotAvailable reason={insights.status === 'FAILED' ? 'The AI insights generation failed for this report.' : 'AI insights are still being generated for this report.'} />
      </SectionCard>
    )
  }

  const findings = getDebtDiagnosisFindings(insights)
  if (!findings) {
    return (
      <SectionCard icon={Sparkles} title="Executive summary">
        {subtitle}
        <NotAvailable reason="These insights were generated in an older format and can't be rendered here — reprocess this lead's insights to refresh them." />
      </SectionCard>
    )
  }

  return (
    <SectionCard icon={Sparkles} title="Executive summary">
      {subtitle}
      <div className="flex items-start gap-2.5 rounded-lg bg-[#efebff] p-3">
        <Sparkles className="mt-0.5 size-4 shrink-0 text-[#7d52f4]" aria-hidden="true" />
        <p className="text-sm text-[#171717]">{findings.executiveSummary}</p>
      </div>
      <div>
        <p className="text-xs font-medium tracking-[0.22px] text-[#a3a3a3] uppercase">Current position</p>
        <p className="mt-1.5 text-sm text-[#171717]">{findings.currentPosition || 'Not stated.'}</p>
      </div>
      {insights.modelVersion && <p className="text-xs text-[#a3a3a3]">Generated by {insights.modelVersion}</p>}
    </SectionCard>
  )
}
