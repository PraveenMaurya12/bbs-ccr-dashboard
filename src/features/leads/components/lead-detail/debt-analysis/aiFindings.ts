import type { DebtAnalysisInsights, DebtDiagnosisFindings } from '../../../types'

function isStringArray(value: unknown): value is string[] {
  return Array.isArray(value) && value.every((item) => typeof item === 'string')
}

function isFindingArray(value: unknown): value is DebtDiagnosisFindings['primaryConcerns'] {
  return (
    Array.isArray(value) &&
    value.every(
      (f) => f && typeof f === 'object' && typeof (f as Record<string, unknown>).title === 'string' && typeof (f as Record<string, unknown>).statement === 'string',
    )
  )
}

/**
 * Runtime guard, not a type assertion: an `AnalysisResult` row written
 * before the full BBS Debt Analysis Module rebuild (seeded data, or a
 * report whose insights were generated by the previous Gemini contract)
 * still has the OLD flat shape (`summary`/`keyObservations`/`concerns`/…)
 * — this never crashes on that older shape, it simply returns null so the
 * caller can render an honest "insights predate this format" state instead
 * of a legacy-shaped panel pretending to be the new one.
 */
export function getDebtDiagnosisFindings(insights: DebtAnalysisInsights | null): DebtDiagnosisFindings | null {
  if (!insights || insights.status !== 'COMPLETED' || !insights.findings) return null
  const f = insights.findings as Record<string, unknown>
  if (typeof f.executiveSummary !== 'string' || typeof f.currentPosition !== 'string') return null
  if (!isFindingArray(f.primaryConcerns) || !isFindingArray(f.secondaryConcerns)) return null
  if (!isStringArray(f.dataGaps)) return null
  return f as unknown as DebtDiagnosisFindings
}
