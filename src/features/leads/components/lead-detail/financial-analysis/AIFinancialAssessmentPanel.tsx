import { Sparkles } from 'lucide-react'

import type { FinancialAnalysisInsights } from '../../../types'
import { FindingList } from './FindingList'
import { getFinancialAssessmentFindings } from './financialFindings'
import { CardDivider, NotAvailable, SectionCard } from '../shared/SectionCard'

/**
 * §10 — AI Financial Assessment: Current Position, What Is Working,
 * Primary Concerns, Liquidity/Cash Flow/Income/Debt Servicing/Borrowing/
 * Transaction Behaviour/Credit Correlation assessments, Possible Drivers,
 * Data Gaps, Investigation Priorities — every statement's own evidence
 * level is shown (never presented as fact when INFERRED). Advisory only —
 * never a finalized decision.
 */
export function AIFinancialAssessmentPanel({ insights }: { insights: FinancialAnalysisInsights | null }) {
  const subtitle = <p className="text-xs text-[#5c5c5c]">Advisory only — never a finalized decision</p>

  if (!insights || insights.status !== 'COMPLETED') {
    return (
      <SectionCard icon={Sparkles} title="AI financial assessment">
        {subtitle}
        <NotAvailable reason={!insights ? 'No AI insights have been generated for this statement yet.' : 'AI insights are still being generated for this statement.'} />
      </SectionCard>
    )
  }

  const findings = getFinancialAssessmentFindings(insights)
  if (!findings) {
    return (
      <SectionCard icon={Sparkles} title="AI financial assessment">
        {subtitle}
        <NotAvailable reason="These insights were generated in an older format and cannot be rendered here — reprocess this statement to refresh them." />
      </SectionCard>
    )
  }

  const assessments: Array<[string, string]> = [
    ['Liquidity', findings.liquidityAssessment],
    ['Cash flow', findings.cashFlowAssessment],
    ['Income', findings.incomeAssessment],
    ['Debt servicing', findings.debtServicingAssessment],
    ['Borrowing', findings.borrowingAssessment],
    ['Transaction behaviour', findings.transactionBehaviourAssessment],
    ['Credit correlation', findings.creditCorrelationAssessment],
  ]

  return (
    <SectionCard icon={Sparkles} title="AI financial assessment">
      {subtitle}
      <div className="flex items-start gap-2.5 rounded-lg bg-[#efebff] p-3">
        <Sparkles className="mt-0.5 size-4 shrink-0 text-[#7d52f4]" aria-hidden="true" />
        <div>
          <p className="text-sm text-[#171717]">{findings.executiveSummary}</p>
          <p className="mt-1 text-sm text-[#5c5c5c]">{findings.financialPosition}</p>
        </div>
      </div>

      <FindingList title="Strengths (what is working)" findings={findings.strengths} />
      {findings.strengths.length > 0 && findings.concerns.length > 0 && <CardDivider />}
      <FindingList title="Concerns" findings={findings.concerns} />

      <CardDivider />
      <div className="grid grid-cols-1 gap-3 sm:grid-cols-2">
        {assessments.map(([label, text]) => (
          <div key={label}>
            <p className="text-xs font-medium tracking-[0.22px] text-[#a3a3a3] uppercase">{label}</p>
            <p className="mt-1 text-sm text-[#171717]">{text || 'Not assessed.'}</p>
          </div>
        ))}
      </div>

      <CardDivider />
      <FindingList title="Possible drivers (root cause)" findings={findings.possibleDrivers} />
      <FindingList title="Data gaps" findings={findings.dataGaps} />
      <FindingList title="Investigation priorities" findings={findings.investigationPriorities} />

      <CardDivider />
      <div>
        <p className="mb-2 text-xs font-medium tracking-[0.22px] text-[#a3a3a3] uppercase">Final BBS assessment</p>
        <div className="flex flex-col gap-2 text-sm text-[#171717]">
          <p><span className="font-medium">What is happening? </span>{findings.overallAssessment.whatIsHappening}</p>
          <p><span className="font-medium">What is the concern? </span>{findings.overallAssessment.whatIsTheConcern}</p>
          <p><span className="font-medium">What supports stability? </span>{findings.overallAssessment.whatSupportsStability}</p>
          <p><span className="font-medium">What requires investigation? </span>{findings.overallAssessment.whatRequiresInvestigation}</p>
          <p><span className="font-medium">What should BBS do next? </span>{findings.overallAssessment.whatShouldBbsDoNext}</p>
        </div>
      </div>

      {insights.modelVersion && <p className="text-xs text-[#a3a3a3]">Generated by {insights.modelVersion}</p>}
    </SectionCard>
  )
}
